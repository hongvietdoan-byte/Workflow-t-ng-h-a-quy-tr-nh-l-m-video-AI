BREATH_S, BREATH_LEVEL = 0.6, 0.05     # D6 (editing.md E4): the music drops to ~-26 dB this long before a turn, so the hit lands


SHAKE_S, SHAKE_PX = 0.25, 10          # D9 (editing.md E6): a hit shakes the frame ~6 frames, up to 10 px, dying away


def shake_filter(times: Sequence[float]) -> str:
    """Crop-based camera shake at each time (the frame is enlarged 2 % so the shake never shows a border), decaying to rest."""
    if not times:
        return ""
    amp = "+".join(f"between(t,{x:.2f},{x + SHAKE_S:.2f})*(1-(t-{x:.2f})/{SHAKE_S})" for x in times)
    return (f"scale=iw*1.02:ih*1.02,crop=w=iw/1.02:h=ih/1.02:"
            f"x='(iw-iw/1.02)/2+{SHAKE_PX}*({amp})*sin(t*90)':y='(ih-ih/1.02)/2+{SHAKE_PX}*({amp})*cos(t*77)'")


def add_shake(src: str, dst: str, times: Sequence[float], ffmpeg: Optional[str] = None) -> str:
    ff = ffmpeg or find_ffmpeg()
    w, h = probe_size(src) or (1080, 1920)
    run([ff, "-y", "-i", src, "-vf", shake_filter(times) + f",scale={w}:{h}", *_ENCODE, "-c:a", "copy", dst])   # the exact frame back
    return dst


PULSE_S, PULSE_ZOOM, PULSE_PX = 0.35, 0.03, 4    # 07/10 (Khủng Long Đỏ): on each beat the frame punches in 3 % and shakes ~4 px, easing out


def music_beats(path: str, start: float = 0.0, until: Optional[float] = None) -> List[float]:
    """The beats of a music file (librosa beat tracker, DSP — no model) on the FILM's timeline: + `start` (the second the music comes
    in), only those before `until`."""
    import tempfile
    import librosa
    with tempfile.TemporaryDirectory() as d:      # 07/10: librosa (soundfile) cannot open .m4a — decode with ffmpeg first
        wav = os.path.join(d, "beats.wav")
        run([find_ffmpeg(), "-y", "-loglevel", "error", "-i", path, "-ac", "1", "-ar", "22050", wav])
        y, sr = librosa.load(wav, sr=22050, mono=True)
    _, frames = librosa.beat.beat_track(y=y, sr=sr)
    times = [round(float(t) + float(start or 0), 3) for t in librosa.frames_to_time(frames, sr=sr)]
    return [t for t in times if until is None or t < until - PULSE_S]


def pulse_filter(beats: Sequence[float], w: int, h: int) -> str:
    """A slight zoom punch + shake on each beat: the frame is scaled up by the beat's envelope (per frame) and cut back to w×h around the
    centre, so no border ever shows. Envelope (1-(t-b)/PULSE_S)^2: in at once, easing out."""
    if not beats:
        return ""
    env = "+".join(f"between(t,{b:.3f},{b + PULSE_S:.3f})*pow(1-(t-{b:.3f})/{PULSE_S},2)" for b in beats)
    return (f"scale=w='trunc({w}*(1+{PULSE_ZOOM}*({env}))/2)*2':h='trunc({h}*(1+{PULSE_ZOOM}*({env}))/2)*2':eval=frame,"
            f"crop={w}:{h}:x='(iw-{w})/2+{PULSE_PX}*({env})*sin(t*83)':y='(ih-{h})/2+{PULSE_PX}*({env})*cos(t*71)'")


def add_pulse(src: str, dst: str, beats: Sequence[float], ffmpeg: Optional[str] = None) -> str:
    ff = ffmpeg or find_ffmpeg()
    w, h = probe_size(src) or (1080, 1920)
    run([ff, "-y", "-i", src, "-vf", pulse_filter(beats, w, h), *_ENCODE, "-c:a", "copy", dst])
    return dst


FLASHBACK_FLASH = 0.25          # white flash in and out of a flashback shot (seconds)
FLASHBACK_LOOK = "eq=saturation=0.55:gamma=1.05,colorbalance=rs=0.08:gs=0.03:bs=-0.08:rm=0.06:bm=-0.06,vignette=angle=PI/4.5"


def flashback_filter(seconds: float) -> str:
    """The memory look of a flashback shot (trial #8, 2026-09-28): warm, washed-out colour, darker edges, a white flash in and out."""
    out_at = max(seconds - FLASHBACK_FLASH, 0.0)
    return (f"{FLASHBACK_LOOK},fade=t=in:st=0:d={FLASHBACK_FLASH}:color=white,"
            f"fade=t=out:st={out_at:.2f}:d={FLASHBACK_FLASH}:color=white")


# S3.6 (kế hoạch sau #8): a transition of its own at each cut, drawn INSIDE the two clips so the film's length never changes (voices,
# subtitles and effects stay where they were placed). cut / match / occlusion / j_cut / l_cut stay plain cuts here — an occlusion is
# designed in the shots' movement (dp.md Q12), a J/L cut is the sound's (flag j_cut).
EDGE_TRANSITIONS = ("flash", "dip", "whip", "zoom_through")
EDGE_S = {"flash": (0.10, 0.20), "dip": (0.25, 0.25), "whip": (0.15, 0.15), "zoom_through": (0.20, 0.20)}   # (tail of A, head of B)


def edge_filter(seconds: float, head: Optional[str] = None, tail: Optional[str] = None, size=None) -> Optional[str]:
    """Video filter for one clip: its own transition at its head and the next shot's at its tail. None when nothing changes.
    zoom_through needs the clip's `size` (W, H): zoompan redraws each frame (crop's width is set once, it cannot grow — tried)."""
    parts, zoom, d = [], [], max(float(seconds), 0.3)
    if tail in EDGE_TRANSITIONS:
        t = min(EDGE_S[tail][0], d / 3)
        st = round(d - t, 3)
        if tail in ("flash", "dip"):
            parts.append(f"fade=t=out:st={st}:d={t}:color={'white' if tail == 'flash' else 'black'}")
        elif tail == "whip":
            parts.append(f"boxblur=luma_radius=24:luma_power=2:chroma_radius=12:enable='gte(t,{st})'")
        else:
            zoom.append(f"if(gte(it,{st}),1+0.6*(it-{st})/{t},1)")
    if head in EDGE_TRANSITIONS:
        t = min(EDGE_S[head][1], d / 3)
        if head in ("flash", "dip"):
            parts.append(f"fade=t=in:st=0:d={t}:color={'white' if head == 'flash' else 'black'}")
        elif head == "whip":
            parts.append(f"boxblur=luma_radius=24:luma_power=2:chroma_radius=12:enable='lt(t,{t})'")
        else:
            zoom.append(f"if(lt(it,{t}),1.6-0.6*it/{t},1)")
    if zoom and size:
        w, h = int(size[0]) // 2 * 2, int(size[1]) // 2 * 2
        z = "*".join(f"({x})" for x in zoom)
        parts.insert(0, f"zoompan=z='{z}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d=1:s={w}x{h}:fps=24")
    return ",".join(parts) or None


